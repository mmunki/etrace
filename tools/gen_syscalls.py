#!/usr/bin/env python3
"""Generate syscall_names.h from the Linux UAPI headers.

The generated table is committed so that a build only needs a C compiler.  It
is regenerated with:

    tools/gen_syscalls.py \
        --x86_64 /usr/include/x86_64-linux-gnu/asm/unistd_64.h \
        --aarch64 /usr/aarch64-linux-gnu/include/asm/unistd_64.h \
        -o syscall_names.h

If the aarch64 header is not available (it comes from
gcc-aarch64-linux-gnu), /usr/include/asm-generic/unistd.h works as well; the
aliases in that file are resolved to their numeric values.
"""
from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict

NUM = re.compile(r"^#define\s+(__NR\w*)\s+(\d+)\s*(?:/\*.*\*/)?\s*$")
ALIAS = re.compile(r"^#define\s+(__NR\w*)\s+(__NR\w*)\s*(?:/\*.*\*/)?\s*$")
SKIP = {"syscalls", "arch_specific_syscall"}


def parse(path: str) -> dict[str, int]:
    raw_num: dict[str, int] = {}
    aliases: list[tuple[str, str]] = []
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            m = NUM.match(line)
            if m:
                raw_num[m.group(1)] = int(m.group(2))
                continue
            m = ALIAS.match(line)
            if m:
                aliases.append((m.group(1), m.group(2)))

    values = dict(raw_num)
    # Aliases can refer to other aliases; a few passes are enough.
    for _ in range(4):
        changed = False
        for name, target in aliases:
            if name not in values and target in values:
                values[name] = values[target]
                changed = True
        if not changed:
            break
    return values


def clean_name(macro: str) -> str:
    """__NR_newfstatat -> newfstatat, __NR3264_fcntl -> fcntl."""
    name = macro[len("__NR"):]
    if name.startswith("3264_"):
        name = name[len("3264_"):]
    elif name.startswith("_"):
        name = name[1:]
    return name


def score(name: str) -> tuple[int, int, str]:
    points = 0
    if name.endswith("64"):
        points += 20
    if name.startswith("compat_"):
        points += 40
    if name.startswith("old_"):
        points += 30
    if name in SKIP:
        points += 100
    return (points, len(name), name)


def build(values: dict[str, int]) -> tuple[list[tuple[int, str]], list[tuple[int, str, str]]]:
    by_nr: dict[int, list[str]] = defaultdict(list)
    for macro, nr in values.items():
        name = clean_name(macro)
        if name in SKIP or not name:
            continue
        by_nr[nr].append(name)

    primary: list[tuple[int, str]] = []
    aliases: list[tuple[int, str, str]] = []
    for nr in sorted(by_nr):
        names = sorted(set(by_nr[nr]), key=score)
        canonical = names[0]
        primary.append((nr, canonical))
        for alias in names[1:]:
            aliases.append((nr, alias, canonical))
    if not aliases:
        aliases.append((0, "", ""))
    return primary, aliases


def emit_array(out, ctype: str, name: str, rows: list[tuple]) -> None:
    out.write(f"static const {ctype} {name}[] = {{\n")
    for row in rows:
        nr = row[0]
        rest = ", ".join(f'"{x}"' for x in row[1:])
        out.write(f"    {{ {nr}u, {rest} }},\n")
    out.write("};\n\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--x86_64", default="/usr/include/x86_64-linux-gnu/asm/unistd_64.h")
    ap.add_argument("--aarch64", default="/usr/aarch64-linux-gnu/include/asm/unistd_64.h")
    ap.add_argument("-o", "--output", default="syscall_names.h")
    args = ap.parse_args()

    arches = {}
    for arch, path in (("x86_64", args.x86_64), ("aarch64", args.aarch64)):
        try:
            values = parse(path)
        except FileNotFoundError:
            print(f"error: {arch} syscall header not found: {path}", file=sys.stderr)
            return 1
        if not values:
            print(f"error: no syscall numbers in {path}", file=sys.stderr)
            return 1
        arches[arch] = build(values)
        print(f"{arch}: {len(arches[arch][0])} syscalls from {path}", file=sys.stderr)

    with open(args.output, "w", encoding="utf-8") as out:
        out.write("/* Generated by tools/gen_syscalls.py -- do not edit by hand. */\n")
        out.write("#ifndef ETRACE_SYSCALL_NAMES_H\n#define ETRACE_SYSCALL_NAMES_H\n\n")
        out.write("#include <stddef.h>\n#include <stdint.h>\n\n")
        out.write("typedef struct {\n    uint32_t nr;\n    const char *name;\n} etrace_syscall_name_t;\n\n")
        out.write("typedef struct {\n    uint32_t nr;\n    const char *alias;\n    const char *name;\n} etrace_syscall_alias_t;\n\n")
        for arch in ("x86_64", "aarch64"):
            primary, aliases = arches[arch]
            tag = arch.replace("-", "_")
            emit_array(out, "etrace_syscall_name_t", f"etrace_syscalls_{tag}", primary)
            emit_array(out, "etrace_syscall_alias_t", f"etrace_syscall_aliases_{tag}", aliases)
        out.write("#endif /* ETRACE_SYSCALL_NAMES_H */\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
